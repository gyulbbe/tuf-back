CREATE SEQUENCE users_seq START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;

CREATE TABLE users (
    id NUMBER DEFAULT users_seq.NEXTVAL PRIMARY KEY,
    user_id VARCHAR2(255) NOT NULL,
    password VARCHAR2(255) NOT NULL,
    name VARCHAR2(50),
    phone VARCHAR2(50),
    tier VARCHAR2(50),
    race VARCHAR2(10) CHECK (race IN ('ZERG', 'TERRAN', 'PROTOSS', 'RANDOM')),
    user_type VARCHAR2(20) CHECK (user_type IN ('ROLE_USER', 'ROLE_MANAGER', 'ROLE_MASTER', 'ROLE_ADMIN')),
    battle_tag VARCHAR2(50),
    status VARCHAR2(10) CHECK (status IN ('ACTIVE', 'BANNED', 'INACTIVE')),
    coin NUMBER,
    photo VARCHAR2(255),
    reg_date DATE DEFAULT SYSDATE,
    update_date DATE DEFAULT SYSDATE
);

CREATE TABLE site_menu_visibility (
    menu_key VARCHAR2(100 CHAR) PRIMARY KEY,
    visible NUMBER(1) DEFAULT 1 NOT NULL,
    updated_by NUMBER,
    updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT chk_site_menu_visibility_visible CHECK (visible IN (0, 1)),
    CONSTRAINT fk_site_menu_visibility_updated_by FOREIGN KEY (updated_by) REFERENCES users(id)
);

