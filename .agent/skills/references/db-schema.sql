CREATE OR REPLACE VIEW v_user_match_results AS
SELECT
    l.id AS league_id,
    l.league_name AS league_name,
    l.league_type AS league_type,
    t.id AS tournament_id,
    m.id AS match_id,
    s.id AS slot_id,
    p.user_id AS user_id,
    u.user_id AS login_id,
    p.id AS participant_id,
    op.user_id AS opponent_user_id,
    ou.user_id AS opponent_login_id,
    CASE WHEN s.is_winner = 1 THEN 'WIN' ELSE 'LOSE' END AS result,
    s.score AS score_for,
    os.score AS score_against,
    s.is_bye AS is_bye,
    m.update_date AS decided_at,
    'TOURNAMENT' AS source_type
FROM leagues l
JOIN tournaments t
    ON t.id = l.tournament_id
JOIN tournament_participants p
    ON p.tournament_id = t.id
JOIN users u
    ON u.id = p.user_id
JOIN tournament_match_slots s
    ON s.participant_id = p.id
   AND s.is_bye = 0
JOIN tournament_matches m
    ON m.id = s.match_id
   AND m.status = 'FINISHED'
   AND m.winner_participant_id IS NOT NULL
JOIN tournament_match_slots os
    ON os.match_id = s.match_id
   AND os.id <> s.id
   AND os.participant_id IS NOT NULL
   AND os.is_bye = 0
JOIN tournament_participants op
    ON op.id = os.participant_id
LEFT JOIN users ou
    ON ou.id = op.user_id
WHERE l.league_type IN ('PERSONAL', 'RACE_SURVIVAL', 'ULTIMATE_BATTLE')
UNION ALL
SELECT
    l.id AS league_id,
    l.league_name AS league_name,
    l.league_type AS league_type,
    CAST(NULL AS NUMBER) AS tournament_id,
    mi.id AS match_id,
    mp.id AS slot_id,
    mp.user_id AS user_id,
    u.user_id AS login_id,
    CAST(NULL AS NUMBER) AS participant_id,
    CAST(NULL AS NUMBER) AS opponent_user_id,
    CAST(NULL AS VARCHAR2(255 CHAR)) AS opponent_login_id,
    mp.result AS result,
    CAST(NULL AS NUMBER) AS score_for,
    CAST(NULL AS NUMBER) AS score_against,
    0 AS is_bye,
    CAST(mi.update_date AS TIMESTAMP) AS decided_at,
    'LEGACY_PROLEAGUE' AS source_type
FROM leagues l
JOIN match_infos mi
    ON mi.league_id = l.id
JOIN match_players mp
    ON mp.match_info_id = mi.id
JOIN users u
    ON u.id = mp.user_id
WHERE l.league_type = 'PROLEAGUE'
  AND mp.result IN ('WIN', 'LOSE', 'DRAW');

CREATE OR REPLACE VIEW v_user_league_records AS
SELECT
    league_id,
    league_name,
    league_type,
    user_id,
    login_id,
    COUNT(CASE WHEN result = 'WIN' THEN 1 END) AS wins,
    COUNT(CASE WHEN result = 'LOSE' THEN 1 END) AS losses,
    COUNT(CASE WHEN result = 'DRAW' THEN 1 END) AS draws,
    SUM(NVL(score_for, 0)) AS score_for,
    SUM(NVL(score_against, 0)) AS score_against,
    MIN(source_type) AS source_type
FROM v_user_match_results
GROUP BY
    league_id,
    league_name,
    league_type,
    user_id,
    login_id;

