    update_date TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_tournament_routes_from_match
        FOREIGN KEY (from_match_id) REFERENCES tournament_matches(id),
    CONSTRAINT fk_tournament_routes_to_match
        FOREIGN KEY (to_match_id) REFERENCES tournament_matches(id),
    CONSTRAINT fk_tournament_routes_result_slot
        FOREIGN KEY (to_result_slot_id) REFERENCES tournament_result_slots(id),
    CONSTRAINT uq_tournament_routes_outcome
        UNIQUE (from_match_id, outcome),
    CONSTRAINT chk_tournament_routes_outcome
        CHECK (outcome IN ('WINNER', 'LOSER')),
    CONSTRAINT chk_tournament_routes_target
        CHECK (target_type IN ('MATCH_SLOT', 'RESULT_SLOT', 'ELIMINATED')),
    CONSTRAINT chk_tournament_routes_to_slot
        CHECK (to_slot_no IS NULL OR to_slot_no IN (1, 2)),
    CONSTRAINT chk_tournament_routes_target_cols
        CHECK (
            (target_type = 'MATCH_SLOT' AND to_match_id IS NOT NULL AND to_slot_no IS NOT NULL AND to_result_slot_id IS NULL)
            OR (target_type = 'RESULT_SLOT' AND to_match_id IS NULL AND to_slot_no IS NULL AND to_result_slot_id IS NOT NULL)
            OR (target_type = 'ELIMINATED' AND to_match_id IS NULL AND to_slot_no IS NULL AND to_result_slot_id IS NULL)
        )
);

